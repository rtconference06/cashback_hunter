import type { DealCandidate } from "@/lib/deals";

function deal(
  id: string,
  title: string,
  category: string,
  priceCents: number,
  cashbackPercent: number,
  store: string,
  keywords: string,
  description: string,
): DealCandidate {
  return {
    id,
    title,
    category,
    priceCents,
    cashbackPercent,
    store,
    keywords,
    description,
    imageUrl: "",
    link: `https://www.rakuten.com/#sample-${id}`,
  };
}

function artFor(id: string): string {
  if (/(mug|bowl)/.test(id)) return "mug";
  if (/(novel|book|birds|crossword|cookbook)/.test(id)) return "book";
  if (/(matcha|tea|teapot)/.test(id)) return "tea";
  if (id.includes("pen")) return "pen";
  if (id.includes("boot")) return "boots";
  if (/(kneeler|garden)/.test(id)) return "garden";
  if (id.includes("sauce")) return "sauce";
  if (id.includes("vinyl")) return "vinyl";
  if (/(sweater|tee|vest|sock)/.test(id)) return "apparel";
  if (id.includes("candle")) return "candle";
  if (id.includes("coffee")) return "coffee";
  if (/(sketch|pencil)/.test(id)) return "art";
  if (id.includes("dino")) return "toy";
  if (id.includes("space")) return "space";
  if (id.includes("candy")) return "candy";
  return "default";
}

